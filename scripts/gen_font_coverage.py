#!/usr/bin/env python3
"""gen_font_coverage.py — 重新生成 report 包的字体覆盖区间表。

输入字体：upstream/hector/internal/researchos/report/fonts/NotoSansSC-Regular.ttf
输出：    upstream/hector/internal/researchos/report/font_coverage_gen.go

什么时候需要重跑：更换了内嵌字体（换字重、换家族、重新子集化）之后。
依赖：pip install fonttools
"""
from __future__ import annotations

import os
import sys

from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT = os.path.join(ROOT, "upstream", "hector", "internal", "researchos", "report", "fonts", "NotoSansSC-Regular.ttf")
OUT = os.path.join(ROOT, "upstream", "hector", "internal", "researchos", "report", "font_coverage_gen.go")


def main() -> int:
    if not os.path.isfile(FONT):
        print(f"找不到字体：{FONT}", file=sys.stderr)
        return 1
    cmap = TTFont(FONT).getBestCmap()
    cps = sorted(cmap)
    ranges: list[tuple[int, int]] = []
    start = prev = None
    for cp in cps:
        if start is None:
            start = prev = cp
        elif cp == prev + 1:
            prev = cp
        else:
            ranges.append((start, prev))
            start = prev = cp
    if start is not None:
        ranges.append((start, prev))

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("// Code generated by scripts/gen_font_coverage.py; DO NOT EDIT.\n\npackage report\n\n")
        fh.write("// fontCoverage 是 NotoSansSC-Regular.ttf 的 cmap 覆盖区间（排序、合并）。\n")
        fh.write("// 不在区间内的码点会在排版前被替换为 '□'，避免 gopdf 报 ErrCharNotFound。\n")
        fh.write("var fontCoverage = [][2]rune{\n")
        for a, b in ranges:
            fh.write(f"\t{{0x{a:X}, 0x{b:X}}},\n")
        fh.write("}\n")
    print(f"已生成 {OUT}（{len(ranges)} 个区间）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
